const I18N_TABLE = new Map(Object.entries(I18N[Lang.current] ?? {}).map(([k, v]) => [normText(k), v]));

// Translates English text (whitespace-insensitive, outer whitespace kept) and fills {placeholders}
function t(text, vars) {
	if (typeof text !== "string")
		return text;
	let out = text;
	const found = I18N_TABLE.get(normText(text));
	if (found !== undefined)
		out = text.slice(0, text.length - text.trimStart().length) + found + text.slice(text.trimEnd().length);
	return vars ? out.replace(/\{(\w+)\}/g, (m, k) => k in vars ? String(vars[k]) : m) : out;
}

// Translates the static page once: attributes, text nodes and mixed-markup elements (matched by innerHTML)
function translatePage() {
	document.documentElement.lang = Lang.current;
	if (!I18N_TABLE.size)
		return;
	document.title = t(document.title);
	const attrs = ["data-title", "aria-label", "alt", "placeholder", "title", "data-name", "data-group"];
	const translateAttrs = el => attrs.forEach(a => el.hasAttribute(a) && el.setAttribute(a, t(el.getAttribute(a))));
	const visit = el => {
		translateAttrs(el);
		if (el.matches("script, style, canvas"))
			return;
		if (el.childElementCount > 0 && el.childElementCount < 10) {
			const html = I18N_TABLE.get(normText(el.innerHTML));
			if (html !== undefined) {
				el.innerHTML = html;
				el.querySelectorAll("*").forEach(translateAttrs);
				return;
			}
		}
		for (const node of [...el.childNodes]) {
			if (node.nodeType === Node.TEXT_NODE)
				node.nodeValue = t(node.nodeValue);
			else if (node.nodeType === Node.ELEMENT_NODE)
				visit(node);
		}
	};
	visit(document.body);
}

